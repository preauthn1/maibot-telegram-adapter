"""群聊"管人"话术拦截。

2026-10-03 某群聊事故：群友在发擦边图，账号 17 分钟内连发十几条
"别发了/撤回吧/能举报就举报/管理员按群规处理"，群友随即
``/admin`` 呼叫管理，账号被踢。

真人群友对尺度内容的常见反应是无视、起哄或沉默，不会当风纪委员。
提示词约束模型不这样说，但不能只靠模型自觉，所以发送前再硬拦一道。

只在群聊生效；私聊里用户主动求助被骗、要求怎么举报时，
相关建议是有用信息，不在这里拦截。
"""

import re

# 劝撤回、威胁/建议举报、报警、喊管理员处理——都属于对群友行为的管束。
# 注意：不能用裸 `撤回(吧|一下|掉)?`（否则连正常解答客户端功能「可以长按消息撤回」「支持双向撤回」都会被误判拦截）。
_POLICING_PATTERNS = (
    re.compile(r"(?:赶紧|快点?|建议|最好|先|请|你|把.{0,6})撤回|撤回(吧|一下|掉|那条|这条)"),
    re.compile(r"(举报|报警|报平台|报警方|向平台反馈)"),
    re.compile(r"(管理员?|群主|群管|有权限的).{0,6}(处理|踢|管|看看|按群规)"),
    re.compile(r"按群规"),
    re.compile(r"别(再)?(发|转|传播|继续发|往).{0,8}(了|图|内容|方向|这类)"),
    re.compile(r"(收一收|收手|收敛点|注意尺度|注意点影响)"),
    # "别往…方向带了" "别继续发" "别再问了" 这类对群友下指令。
    re.compile(r"别(再|继续)?往.{0,10}带"),
    re.compile(r"别(再|继续)(发|转|问|聊|带)"),
    re.compile(r"(幼态|未成年|性暗示|性化|露骨|擦边|性骚扰).{0,12}(别|不行|不看|不回答|不聊)"),
    re.compile(r"(别|不行|不看|不回答|不聊).{0,12}(幼态|未成年|性暗示|性化|露骨|擦边|性骚扰)"),
)


def is_group_policing(text: str) -> bool:
    """判断回复是否在管束群友行为（劝撤回、提举报、喊管理）。

    Args:
        text: 待发送文本。

    Returns:
        bool: 命中管人话术返回 ``True``。
    """

    compact = re.sub(r"\s+", "", text)
    return any(pattern.search(compact) for pattern in _POLICING_PATTERNS)
